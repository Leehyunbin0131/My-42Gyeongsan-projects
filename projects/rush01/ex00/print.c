#include <unistd.h>

void	print(int **arr, int num)
{
	int	i;
	int	j;
	int	max;

	i = 1;
	max = num - 2;
	while (i <= max)
	{
		j = 1;
		while (j <= max)
		{
			write (1, (char []){arr[i][j] + '0'}, 1);
			if (!(j == max))
				write (1, " ", 1);
			if (j == max)
				write (1, "\n", 1);
			j++;
		}
		i++;
	}
}
