void	sort_by_second_desc(int arr[][2], int n)
{
	int	i;
	int	j;
	int	tmp[2];

	i = 0;
	while (i < n - 1)
	{
		j = 0;
		while (j < n - 1 - i)
		{
			if (arr[j][1] < arr[j + 1][1])
			{
				tmp[0] = arr[j][0];
				tmp[1] = arr[j][1];
				arr[j][0] = arr[j + 1][0];
				arr[j][1] = arr[j + 1][1];
				arr[j + 1][0] = tmp[0];
				arr[j + 1][1] = tmp[1];
			}
			j++;
		}
		i++;
	}
}
